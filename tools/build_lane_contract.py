"""Build LANE-CONTRACT.md from contract/*.md (the step files are the source).

INDEX: generate LANE-CONTRACT.md from the contract/ floor and step files; --check fails when stale

LANE-CONTRACT.md is GENERATED: floor, knowledge, reasoning, judgement, review,
keyrun, concatenated in that order with one blank line between files. Floor text
lives only in contract/floor.md and is never hand-duplicated.

Usage:
  python tools/build_lane_contract.py --write   regenerate LANE-CONTRACT.md
  python tools/build_lane_contract.py --check   exit 1 if LANE-CONTRACT.md is stale
  python tools/build_lane_contract.py --sizes   print bytes per step (floor + step)
Exit codes: 0 ok, 1 stale or missing source, 2 usage error.
"""

import os
import sys

ORDER = ("floor", "knowledge", "reasoning", "judgement", "review", "keyrun")
STEPS = ("knowledge", "reasoning", "judgement", "review")
BANNER = ("<!-- GENERATED by tools/build_lane_contract.py from contract/*.md. "
          "Do not edit: edit the contract/ file, then run --write. -->")

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _read(path):
    """Read a text file as UTF-8 with LF newlines."""
    with open(path, encoding="utf-8", newline="") as fh:
        return fh.read().replace("\r\n", "\n")


def build(root=REPO_ROOT):
    """Return the generated LANE-CONTRACT.md text for the checkout at root."""
    parts = []
    for name in ORDER:
        path = os.path.join(root, "contract", name + ".md")
        if not os.path.isfile(path):
            raise FileNotFoundError(path)
        parts.append(_read(path).strip("\n"))
    text = "\n\n".join(parts) + "\n"
    first, _, rest = text.partition("\n")
    return first + "\n" + BANNER + "\n" + rest


def is_fresh(root=REPO_ROOT):
    """True when LANE-CONTRACT.md equals the build output."""
    target = os.path.join(root, "LANE-CONTRACT.md")
    if not os.path.isfile(target):
        return False
    return _read(target) == build(root)


def sizes(root=REPO_ROOT):
    """Return {step: bytes of floor + step} plus 'full' for the generated file."""
    def size(name):
        return os.path.getsize(os.path.join(root, "contract", name + ".md"))
    out = {step: size("floor") + size(step) for step in STEPS}
    out["full"] = len(build(root).encode("utf-8"))
    return out


def main(argv=None):
    args = list(sys.argv[1:] if argv is None else argv)
    if len(args) != 1 or args[0] not in ("--write", "--check", "--sizes"):
        sys.stderr.write(__doc__)
        return 2
    try:
        if args[0] == "--write":
            with open(os.path.join(REPO_ROOT, "LANE-CONTRACT.md"), "w",
                      encoding="utf-8", newline="\n") as fh:
                fh.write(build())
            print("wrote LANE-CONTRACT.md")
            return 0
        if args[0] == "--sizes":
            for key, value in sizes().items():
                print("%s %d" % (key, value))
            return 0
        if is_fresh():
            print("LANE-CONTRACT.md is fresh")
            return 0
        print("STALE: LANE-CONTRACT.md differs from contract/*.md; run "
              "python tools/build_lane_contract.py --write")
        return 1
    except FileNotFoundError as exc:
        print("MISSING SOURCE: %s" % exc)
        return 1


if __name__ == "__main__":
    sys.exit(main())
