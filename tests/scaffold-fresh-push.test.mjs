// End-to-end: a freshly scaffolded project can push to a fresh remote.
// Contract under test (fix/fresh-scaffold-can-push):
//  - `aesop <target>` generates tools/INDEX.md and every push-gate baseline the
//    pre-push hook reads from the scaffolded tree. They are left for the adopter's
//    first commit (the README flow: scaffold, then git add/commit, then push).
//  - With no trunk ref on origin, the hook enters BOOTSTRAP mode: it prints
//    "BOOTSTRAP: no trunk on origin; base = HEAD" and reads baselines from HEAD.
//  - Bootstrap fails closed when a required baseline is absent from HEAD, naming it.
//  - When a trunk exists on origin (origin/HEAD, origin/main, origin/master), base
//    resolution uses it and bootstrap never applies.
//
// Isolation: HOME/USERPROFILE point at a temp dir; the remote is a local bare repo.
// No network.
//
// Run: node --test tests/scaffold-fresh-push.test.mjs

import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { gitCmd } from './helpers/git-helpers.mjs';
import { timedSpawnSync } from './helpers/timed-spawn.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const CLI = path.join(ROOT, 'bin', 'cli.js');

// Every file the scaffold must generate (the hook reads the first three; the
// last two are CI ratchets that doctor also checks).
const GENERATED = [
  'tools/INDEX.md',
  '.pyflakes-baseline.json',
  '.subprocess-guard-baseline.json',
  '.portability-baseline.json',
  '.stateapi-baseline.json'
];
const BOOTSTRAP_BANNER = 'BOOTSTRAP: no trunk on origin; base = HEAD';

function timeoutMs() {
  return Number(process.env.AESOP_TEST_CHILD_TIMEOUT_MS) || 120000;
}

function sandbox() {
  const base = fs.mkdtempSync(path.join(os.tmpdir(), 'aesop-freshpush-'));
  const home = path.join(base, 'home');
  fs.mkdirSync(home, { recursive: true });
  const env = { ...process.env, HOME: home, USERPROFILE: home, GIT_TERMINAL_PROMPT: '0' };
  return { base, env };
}

function scaffold(base, env, name) {
  const res = timedSpawnSync(process.execPath, [CLI, name, '--no-skills'], {
    cwd: base,
    encoding: 'utf8',
    env,
    timeout: timeoutMs(),
    killSignal: 'SIGKILL'
  }, 'scaffold');
  assert.equal(res.status, 0, `scaffold failed. stdout: ${res.stdout}\nstderr: ${res.stderr}`);
  return path.join(base, name);
}

// The README flow after scaffolding: the adopter commits everything, including the
// generated push-gate artifacts, before the first push.
function adopterFirstCommit(target) {
  gitCmd(target, ['add', '-A']);
  gitCmd(target, ['commit', '-q', '-m', 'Adopter first commit']);
}

// One scaffold + one adopter commit per test file, shared by every test. Each test
// gets its own fs.cpSync copy (own repo, remote, HOME and TMPDIR), so no test sees
// another's writes. Scaffolding is the expensive step (git init/add/commit over ~600
// files, ~3s locally and the step that exceeded the spawnSync cap on CI); the assertions
// below still exercise the real scaffold and the real hook on every copy.
let template = null;
function scaffoldedTemplate() {
  if (!template) {
    const { base, env } = sandbox();
    const target = scaffold(base, env, 'fresh-fleet');
    adopterFirstCommit(target);
    template = { base, target };
  }
  return template;
}

function freshCopy() {
  const { base, env } = sandbox();
  const target = path.join(base, 'fresh-fleet');
  fs.cpSync(scaffoldedTemplate().target, target, { recursive: true });
  return { base, env, target };
}

function bareRemote(base) {
  const remote = path.join(base, 'remote.git');
  const res = timedSpawnSync('git', ['init', '--bare', '-q', remote], { encoding: 'utf8' }, 'bare-remote');
  assert.equal(res.status, 0, res.stderr);
  return remote;
}

function push(target, env, branch, label) {
  return timedSpawnSync('git', ['push', 'origin', `HEAD:refs/heads/${branch}`], {
    cwd: target,
    encoding: 'utf8',
    env,
    timeout: timeoutMs(),
    killSignal: 'SIGKILL'
  }, label);
}

function output(res) {
  return `${res.stdout || ''}\n${res.stderr || ''}`;
}

test('fresh scaffold generates every push-gate artifact and the adopter commit carries them', () => {
  const { target } = scaffoldedTemplate();
  for (const file of GENERATED) {
    assert.ok(fs.existsSync(path.join(target, file)), `${file} must be generated by the scaffold`);
  }
  for (const file of GENERATED) {
    const inHead = timedSpawnSync('git', ['cat-file', '-e', `HEAD:${file}`], { cwd: target }, 'cat-file');
    assert.equal(inHead.status, 0, `${file} must be in the adopter's first commit`);
  }
});

test('fresh scaffold pushes a feature branch to an empty remote (bootstrap mode)', () => {
  const { base, env, target } = freshCopy();
  const remote = bareRemote(base);
  gitCmd(target, ['remote', 'add', 'origin', remote]);

  const res = push(target, env, 'feature/smoke', 'bootstrap-push');
  assert.equal(res.status, 0, `push must succeed on a fresh remote.\n${output(res)}`);
  assert.ok(output(res).includes(BOOTSTRAP_BANNER), `bootstrap banner expected.\n${output(res)}`);

  const branches = timedSpawnSync('git', ['ls-remote', '--heads', remote, 'feature/smoke'], { encoding: 'utf8' }, 'ls-remote');
  assert.match(branches.stdout, /refs\/heads\/feature\/smoke/, 'branch must exist on the remote');
});

test('bootstrap fails closed when a required baseline is absent from HEAD, naming it', () => {
  const { base, env, target } = freshCopy();
  const remote = bareRemote(base);
  gitCmd(target, ['remote', 'add', 'origin', remote]);
  gitCmd(target, ['rm', '-q', '.subprocess-guard-baseline.json']);
  gitCmd(target, ['commit', '-q', '-m', 'drop subprocess baseline']);

  const res = push(target, env, 'feature/smoke', 'blocked-push');
  assert.notEqual(res.status, 0, `push must be blocked without the baseline.\n${output(res)}`);
  assert.ok(
    output(res).includes('.subprocess-guard-baseline.json'),
    `the blocking message must name the missing file.\n${output(res)}`
  );
  assert.ok(
    output(res).includes('tools/subprocess_guard.py'),
    `the blocking message must name the regenerate command.\n${output(res)}`
  );
});

test('trunk master on origin: base resolution uses it and bootstrap does not apply', () => {
  const { base, env, target } = freshCopy();
  const remote = bareRemote(base);

  // Seed origin/master from a hook-free clone of the scaffold (a clone has no
  // pre-push hook installed, so this seeding push is not gated). The seed adds one
  // empty commit so the trunk sha differs from the adopter's HEAD: the base gate copy
  // is keyed by the base sha, which lets the test observe which commit was used.
  const seed = path.join(base, 'seed');
  const cloned = timedSpawnSync('git', ['clone', '-q', target, seed], { encoding: 'utf8', env }, 'clone-seed');
  assert.equal(cloned.status, 0, cloned.stderr);
  gitCmd(seed, ['-c', 'user.email=seed@example.com', '-c', 'user.name=Seed', 'commit', '-q', '--allow-empty', '-m', 'trunk']);
  gitCmd(seed, ['push', '-q', remote, 'HEAD:refs/heads/master']);
  const trunkSha = gitCmd(seed, ['rev-parse', 'HEAD']).stdout.trim();

  gitCmd(target, ['remote', 'add', 'origin', remote]);
  gitCmd(target, ['fetch', '-q', 'origin']);
  const headSha = gitCmd(target, ['rev-parse', 'HEAD']).stdout.trim();
  assert.notEqual(trunkSha, headSha, 'fixture: trunk and HEAD must differ');

  const tmpRoot = path.join(base, 'tmp');
  fs.mkdirSync(tmpRoot, { recursive: true });
  const res = push(target, { ...env, TMPDIR: tmpRoot }, 'feature/smoke', 'trunk-push');
  assert.equal(res.status, 0, `push must succeed with master as trunk.\n${output(res)}`);
  assert.ok(!output(res).includes(BOOTSTRAP_BANNER), `bootstrap must not apply once a trunk exists.\n${output(res)}`);
  // The base gate copies were extracted from the trunk commit, not from HEAD.
  assert.ok(
    fs.existsSync(path.join(tmpRoot, `aesop-gate-base-v3-${trunkSha}`, '.complete')),
    'base gate copy must be extracted from origin/master (the trunk), not HEAD'
  );
});
