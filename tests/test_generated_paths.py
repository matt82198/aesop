#!/usr/bin/env python3

"""Generated-path registry (tools/generated_paths.py) + pre-push gate tests.

Three parts:
  1. The registry itself -- declaration shape, is_generated() matching rules,
     and the --list/--check CLI exit-code contract including the
     AESOP_ALLOW_GENERATED=1 designed-writer escape hatch.
  2. The pre-push wiring -- hooks/pre-push-policy.sh check_generated_paths() is
     sourced and driven directly against fixture git repos, proving it REJECTS a
     push whose diff touches a registered path, PASSES an ordinary push, and
     honors the escape hatch.
  3. The registration contract -- registry membership pinned against the real
     gates, plus the wedge this file was extended to prevent and the rule that
     registering an artifact must not turn a hand-edit into a silent auto-fix.

The registry exists so that unattended automation (the merge queue's
`worktree_is_safe` / `restore_generated_paths` / `regenerate_on_batch`) can
discard and rebuild files this repository GENERATES, and nothing else.

These tests pin the membership of that registry against the real gates, and
prove the specific wedge this file was extended to prevent: `tools/INDEX.md`
is generated by `tools/gen_tool_index.py` and guarded by a byte-identity
check, but was not registered -- so a batch whose union drifted it could not
be repaired by the queue and the queue could not publish the batch.

They also pin the interaction the registration must NOT break: registering a
generated artifact must not turn a genuine hand-edit into a silent auto-fix.
"""

