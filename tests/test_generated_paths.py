def _run(argv, cwd):
    """Run a python tool with an explicit cwd and utf-8 decoding."""
    return subprocess.run(
        [sys.executable] + [str(a) for a in argv],
        cwd=str(cwd), capture_output=True, text=True,
        encoding="utf-8", errors="replace", timeout=120)


def _git(args, cwd):
    """git with identity forced per-invocation: never touches global config."""
    return subprocess.run(
        ["git", "-c", "user.email=t@example.invalid", "-c", "user.name=t"] + args,
        cwd=str(cwd), capture_output=True, text=True,
        encoding="utf-8", errors="replace", timeout=120)


class ToolsRepoFixture(unittest.TestCase):
    """A throwaway git repo containing a real copy of gen_tool_index.py.

    Hermetic: a temp dir, its own git repo, per-invocation git identity, and
    the process cwd is never changed.
    """

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory(prefix="aesop-genpaths-")
        self.root = Path(self._tmp.name)
        self.addCleanup(self._tmp.cleanup)
        (self.root / "tools").mkdir()
        # The generator under test is the real one, not a stand-in.
        (self.root / "tools" / "gen_tool_index.py").write_text(
            GEN_TOOL_INDEX.read_text(encoding="utf-8"),
            encoding="utf-8", newline="\n")
        self.assertEqual(_git(["init", "-q"], self.root).returncode, 0)
        self.add_tool("alpha.py", "alpha purpose")
        self.regenerate()

    def add_tool(self, name, index_line):
        """Add a tracked tools/<name> carrying (or omitting) an INDEX: line."""
        body = ['#!/usr/bin/env python3', '"""Doc.']
        if index_line is not None:
            body.append("INDEX: %s" % index_line)
        body += ['"""', ""]
        (self.root / "tools" / name).write_text(
            "\n".join(body), encoding="utf-8", newline="\n")
        self.assertEqual(
            _git(["add", "--", "tools/%s" % name], self.root).returncode, 0)

    def check(self):
        """The byte-identity gate. 0 = in sync, 1 = drift or missing INDEX:."""
        return _run([GEN_TOOL_INDEX, "--root", self.root, "--check"], self.root)

    def regenerate(self):
        return _run(
            [GEN_TOOL_INDEX, "--root", self.root, "--regenerate"], self.root)

    def index_bytes(self):
        p = self.root / "tools" / "INDEX.md"
        return p.read_bytes() if p.exists() else None


class TestPredictedIndexWedge(ToolsRepoFixture):
    """The jam: a batch union drifts INDEX.md and nothing can repair it.

    Every member of an integration batch can be individually green while their
    union is not: each member adds a tool with its own INDEX: line, so each
    branch's INDEX.md is byte-identical to its own sources, and the merged tree
    is missing the other member's entry. The byte-identity gate then fails
    closed on a branch the queue already built -- the exact shape of the
    suite-count jam this registry was created for.
    """

    def test_union_of_two_green_members_drifts_the_index_gate(self):
        """Repro: each member alone is green; the union fails the gate."""
        self.assertEqual(self.check().returncode, 0, "baseline must be in sync")
        # Member A and member B each land a tool. Neither regenerates on top of
        # the other -- the merge does, and no member ever tested that tree.
        self.add_tool("beta.py", "beta purpose")
        self.add_tool("gamma.py", "gamma purpose")
        proc = self.check()
        self.assertEqual(proc.returncode, 1, proc.stdout + proc.stderr)
        self.assertIn("out of date", proc.stderr)

    def test_index_md_is_a_registered_generated_path(self):
        """Without registration the queue can neither restore nor commit it."""
        self.assertIn("tools/INDEX.md", generated_paths.GENERATED_PATHS)
        self.assertTrue(generated_paths.is_generated("tools/INDEX.md"))
        # Windows porcelain output arrives with backslashes.
        self.assertTrue(generated_paths.is_generated("tools\\INDEX.md"))

    def test_unregistered_drift_would_be_rejected_as_overreach(self):
        """The precise mechanism of the wedge, asserted against real code.

        `regenerate_on_batch` commits a dirty path only when it is in the
        registry; anything else is `regenerator_overreach` and NOTHING is
        committed -- so before registration, an INDEX.md drift on the batch
        branch could not be repaired even if a generator had written it.
        """
        merge_queue = _load("merge_queue_under_test", TOOLS / "merge_queue.py")
        dirty = ["tools/INDEX.md"]
        unregistered = [p for p in dirty if p not in merge_queue.GENERATED_PATHS]
        self.assertEqual(
            unregistered, [],
            "tools/INDEX.md is dirty-but-unregistered: regenerate_on_batch "
            "would row regenerator_overreach and commit nothing, and "
            "worktree_is_safe would refuse the whole pass")

    def test_a_registered_regenerator_repairs_the_drifted_union(self):
        """After registration the queue has a generator that closes the gate."""
        merge_queue = _load("merge_queue_under_test", TOOLS / "merge_queue.py")
        argvs = [tuple(a) for a in merge_queue.REGENERATORS]
        self.assertIn(("tools/gen_tool_index.py", "--regenerate"), argvs)
        # And that generator really does repair the drifted union.
        self.add_tool("beta.py", "beta purpose")
        self.assertEqual(self.check().returncode, 1)
        self.assertEqual(self.regenerate().returncode, 0)
        self.assertEqual(self.check().returncode, 0)

    def test_every_registered_regenerator_accepts_its_flags(self):
        """A registry naming a flag the script rejects fails on every batch."""
        merge_queue = _load("merge_queue_under_test", TOOLS / "merge_queue.py")
        for argv in merge_queue.REGENERATORS:
            script = REPO_ROOT / argv[0]
            self.assertTrue(script.exists(), "missing generator: %s" % argv[0])
            proc = _run([script, "--help"], REPO_ROOT)
            self.assertEqual(proc.returncode, 0, proc.stderr[:300])
            for flag in argv[1:]:
                self.assertIn(flag, proc.stdout,
                              "%s does not accept %s" % (argv[0], flag))


class TestRegistrationDoesNotWeakenTheByteIdentityGate(ToolsRepoFixture):
    """Registration must not make tampering silently auto-fixed.

    The worry is real and worth stating: adding a byte-identity-gated file to
    a registry that unattended automation may `git restore` and regenerate
    could, in principle, launder a hand-edit into green.

    It does not, because the registry's membership criterion is that the file
    is DERIVED. `tools/INDEX.md` is a pure function of the `INDEX:` lines in
    the tools/ sources, so the only edit registration can discard is an edit to
    the derived artifact itself -- which carries no information by
    construction. Every edit that means something lives in a source file, is
    NOT registered, and still faces the unchanged gate.
    """

    def test_regeneration_is_a_pure_function_of_the_sources(self):
        """A hand-edit to INDEX.md alone is information-free: regenerating
        reproduces the same bytes from unchanged sources."""
        before = self.index_bytes()
        p = self.root / "tools" / "INDEX.md"
        p.write_text(
            p.read_text(encoding="utf-8") + "\n- `ghost.py` -- invented\n",
            encoding="utf-8", newline="\n")
        self.assertEqual(self.check().returncode, 1, "the gate still sees it")
        self.assertEqual(self.regenerate().returncode, 0)
        self.assertEqual(self.index_bytes(), before)

    def test_a_tool_with_no_index_line_still_fails_closed(self):
        """The tamper that matters: registration cannot launder an
        undocumented tool into a green index. --regenerate refuses to write."""
        before = self.index_bytes()
        self.add_tool("sneaky.py", None)
        proc = self.regenerate()
        self.assertEqual(proc.returncode, 1, proc.stdout)
        self.assertIn("fail-closed", proc.stderr)
        self.assertEqual(self.index_bytes(), before,
                         "a failing generator must leave the tree untouched")
        self.assertEqual(self.check().returncode, 1)

    def test_editing_a_source_index_line_propagates_it_visibly(self):
        """Ground truth is the source, never the artifact: a tampered INDEX:
        line surfaces IN the regenerated index, in the diff, under review --
        it is not swallowed."""
        self.add_tool("alpha.py", "TAMPERED purpose")
        self.assertEqual(self.check().returncode, 1)
        self.assertEqual(self.regenerate().returncode, 0)
        body = (self.root / "tools" / "INDEX.md").read_text(encoding="utf-8")
        self.assertIn("TAMPERED purpose", body)

    def test_the_gate_itself_is_unchanged_by_registration(self):
        """Registration adds a repair path on the batch branch; it removes no
        check. The pushed branch and CI still run the same byte-identity gate,
        which still fails closed on drift."""
        self.add_tool("beta.py", "beta purpose")
        proc = self.check()
        self.assertEqual(proc.returncode, 1)
        self.assertIn("gen_tool_index.py --regenerate", proc.stderr)


class TestRegistryContract(unittest.TestCase):
    """Regression cover for the paths that were already registered."""

    def test_previously_registered_paths_survive(self):
        for path in ("tests/CLAUDE.md", "tools/CLAUDE.md"):
            self.assertIn(path, generated_paths.GENERATED_PATHS)
            # is_restorable() is the predicate for the automation-restorable
            # tuple. is_generated() answers the narrower REGISTRY question
            # (every byte machine-written) that drives the push-blocking gate,
            # and these two prose-carrying docs are deliberately NOT in it.
            self.assertTrue(generated_paths.is_restorable(path))
            self.assertIsNone(generated_paths.is_generated(path))

    def test_index_md_is_in_both_registries(self):
        """tools/INDEX.md is fully generated AND needs union repair in a batch."""
        self.assertIn("tools/INDEX.md", generated_paths.GENERATED_PATHS)
        self.assertTrue(generated_paths.is_restorable("tools/INDEX.md"))
        self.assertIsNotNone(generated_paths.is_generated("tools/INDEX.md"))

    def test_registry_is_an_immutable_ascii_posix_tuple(self):
        registry = generated_paths.generated_paths()
        self.assertIsInstance(registry, tuple)
        self.assertEqual(registry, generated_paths.GENERATED_PATHS)
        for path in registry:
            self.assertEqual(path, path.encode("ascii").decode("ascii"))
            self.assertNotIn("\\", path)
            self.assertFalse(os.path.isabs(path))

    def test_registry_has_no_duplicates_and_is_sorted(self):
        registry = generated_paths.generated_paths()
        self.assertEqual(len(set(registry)), len(registry))
        self.assertEqual(list(registry), sorted(registry))

    def test_non_members_and_junk_are_not_generated(self):
        for path in ("tools/merge_queue.py", "README.md", "", None,
                     "tools/INDEX.md.bak", "docs/INDEX.md"):
            self.assertFalse(generated_paths.is_generated(path), path)

    def test_every_registered_path_is_tracked_in_this_repo(self):
        """Criterion 3: an untracked file is never restorable, never generated."""
        proc = _git(["ls-files", "--"] + list(generated_paths.GENERATED_PATHS),
                    REPO_ROOT)
        self.assertEqual(proc.returncode, 0, proc.stderr)
        tracked = set(proc.stdout.split())
        self.assertEqual(set(generated_paths.GENERATED_PATHS) - tracked, set())

    def test_merge_queue_shares_the_registry_and_does_not_relist(self):
        merge_queue = _load("merge_queue_under_test", TOOLS / "merge_queue.py")
        self.assertEqual(tuple(merge_queue.GENERATED_PATHS),
                         tuple(generated_paths.GENERATED_PATHS))



class TestMergeCarriedGeneratedPath(unittest.TestCase):
    """A registered generated path that reaches the push only because the branch
    MERGED origin/main is not a touched path: its blob at the push head equals
    origin/main's (or the merge-base's). A hand edit or a real regeneration still
    blocks. Red-first: the pre-fix gate blocked the merge-carried case."""

    INDEX = "tools/INDEX.md"

    def setUp(self):
        # Hosted Linux CI saw `Directory not empty: origin/.git` on rmtree in
        # tearDown (one run, ci shard 0). Cleanup-only tolerance: every assertion
        # still runs; a leftover temp dir is not a test failure.
        self._tmp = tempfile.TemporaryDirectory(ignore_cleanup_errors=True)
        self.tmp = Path(self._tmp.name)
        self.driver = self.tmp / "drive.sh"
        self.driver.write_text(
            '#!/usr/bin/env bash\n'
            '. "%s"\n'
            'check_generated_paths\n'
            'exit $?\n' % HOOK.as_posix(),
            encoding="utf-8", newline="\n")
        self.origin = self.tmp / "origin"
        self.work = self.tmp / "work"
        self.origin.mkdir()
        self.git(self.origin, "init", "-q", "-b", "main")
        self._write(self.origin, "seed.txt", "seed\n")
        # The hook judges gate code from origin/main:tools (gate_base_dir), so the
        # fixture's origin/main must carry the real tools/ tree.
        shutil.copytree(REPO_ROOT / "tools", self.origin / "tools",
                        ignore=shutil.ignore_patterns("__pycache__"))
        self._write(self.origin, self.INDEX, "index v1\n")
        self.git(self.origin, "add", "-A")
        self.git(self.origin, "commit", "-q", "-m", "base")
        self.git(self.tmp, "clone", "-q", str(self.origin), str(self.work))
        self.git(self.work, "checkout", "-q", "-b", "feature/lane")
        self._write(self.work, "feature.txt", "feature\n")
        self.git(self.work, "add", "-A")
        self.git(self.work, "commit", "-q", "-m", "feature work")
        self.base = self.rev(self.work, "HEAD")

    def tearDown(self):
        self._tmp.cleanup()

    def git(self, repo, *args):
        # Identity per invocation (-c), never written into any git config.
        proc = subprocess.run(  # subprocess-ok
            ["git", "-c", "user.email=test@example.invalid",
             "-c", "user.name=Test User"] + list(args), cwd=str(repo),
            capture_output=True, text=True, encoding="utf-8", errors="replace",
            timeout=120)
        self.assertEqual(proc.returncode, 0, proc.stderr)
        return proc.stdout.strip()

    def rev(self, repo, ref):
        return self.git(repo, "rev-parse", ref)

    @staticmethod
    def _write(repo, rel, text):
        path = repo / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")

    def advance_main(self, text):
        """origin/main moves: commit new INDEX.md bytes on main, fetch into work."""
        self._write(self.origin, self.INDEX, text)
        self.git(self.origin, "add", "-A")
        self.git(self.origin, "commit", "-q", "-m", "main regenerates index")
        self.git(self.work, "fetch", "-q", "origin")

    def merge_main(self):
        """The lane merges origin/main into its branch; returns the push head."""
        self.git(self.work, "merge", "-q", "--no-edit", "origin/main")
        return self.rev(self.work, "HEAD")

    def commit_index(self, text):
        self._write(self.work, self.INDEX, text)
        self.git(self.work, "add", "-A")
        self.git(self.work, "commit", "-q", "-m", "lane edits index")
        return self.rev(self.work, "HEAD")

    def run_gate(self, head, env_extra=None):
        run_env = dict(os.environ)
        run_env.pop(generated_paths.ALLOW_ENV, None)
        run_env["AESOP_ROOT"] = REPO_ROOT.as_posix()
        if env_extra:
            run_env.update(env_extra)
        stdin_text = "refs/heads/feature/lane %s refs/heads/feature/lane %s\n" % (
            head, self.base)
        stdin_path = self.tmp / "prepush-stdin.txt"
        stdin_path.write_bytes(stdin_text.encode("utf-8"))
        with open(stdin_path, "rb") as handle:
            return subprocess.run(  # subprocess-ok
                [BASH, str(self.driver)], cwd=str(self.work),
                stdin=handle, capture_output=True, text=True,
                encoding="utf-8", timeout=120, env=run_env)

    def test_merge_carried_index_is_not_blocked(self):
        """Main changed INDEX.md; the branch merged main and nothing else touched it."""
        self.advance_main("index v2 from main\n")
        head = self.merge_main()
        res = self.run_gate(head)
        self.assertEqual(res.returncode, 0, res.stdout + res.stderr)
        self.assertNotIn("BLOCKED", res.stderr)

    def test_control_hand_edit_after_merge_is_still_blocked(self):
        self.advance_main("index v2 from main\n")
        self.merge_main()
        head = self.commit_index("index v3 hand edited\n")
        res = self.run_gate(head)
        self.assertEqual(res.returncode, 1, res.stdout + res.stderr)
        self.assertIn(self.INDEX, res.stderr)

    def test_control_real_regeneration_still_needs_the_override(self):
        self.advance_main("index v2 from main\n")
        self.merge_main()
        head = self.commit_index("index v4 regenerated with real changes\n")
        blocked = self.run_gate(head)
        self.assertEqual(blocked.returncode, 1, blocked.stdout + blocked.stderr)
        self.assertIn(self.INDEX, blocked.stderr)
        allowed = self.run_gate(head, {generated_paths.ALLOW_ENV: "1"})
        self.assertEqual(allowed.returncode, 0, allowed.stdout + allowed.stderr)

    def test_no_origin_main_fails_closed(self):
        """Without origin/main the carried-exemption cannot be proven: still blocked."""
        self.git(self.work, "update-ref", "-d", "refs/remotes/origin/main")
        head = self.commit_index("index v5 no origin ref\n")
        res = self.run_gate(head)
        self.assertEqual(res.returncode, 1, res.stdout + res.stderr)


class TestRegeneratedIdenticalGeneratedPath(TestMergeCarriedGeneratedPath):
    """A registered generated path whose pushed bytes ARE the registered
    generator's output is not a hand edit, even when the push touches it.

    The defect (PR #1018): a lane merged origin/main, the merge carried main's
    tools/INDEX.md, and the lane then left the file at the generator's output
    (working tree == HEAD == generator output). The bytes equal neither the
    merge-base nor origin/main, so the carried-exemption did not apply and the
    gate blocked a push whose content is exactly what tools/gen_tool_index.py
    produces. The fix runs the registered generator on the pushed tree in a
    throwaway checkout and allows the path when the pushed bytes match. A hand
    edit, a missing or crashing generator, and an unverifiable path are still
    blocked; AESOP_ALLOW_GENERATED=1 is unchanged.

    Inherits the fixture (origin/main carries the real tools/ tree) and the
    helpers from TestMergeCarriedGeneratedPath.
    """

    def generated_index(self):
        """Bytes the registered generator writes for the fixture origin tree."""
        proc = subprocess.run(  # subprocess-ok
            [sys.executable, "tools/gen_tool_index.py", "--regenerate"],
            cwd=str(self.origin), capture_output=True, text=True,
            encoding="utf-8", errors="replace", timeout=120)
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
        return (self.origin / self.INDEX).read_bytes()

    def commit_bytes(self, repo, data):
        (repo / self.INDEX).write_bytes(data)
        self.git(repo, "add", "-A")
        self.git(repo, "commit", "-q", "-m", "lane regenerates index")
        return self.rev(repo, "HEAD")

    def test_merged_then_regenerated_index_is_allowed(self):
        """Red on the pre-fix gate: merge carried main, lane left generator output."""
        generated = self.generated_index()
        self.advance_main("index v2 from main\n")
        self.merge_main()
        head = self.commit_bytes(self.work, generated)
        res = self.run_gate(head)
        self.assertEqual(res.returncode, 0, res.stdout + res.stderr)
        self.assertNotIn("BLOCKED", res.stderr)

    def test_regenerated_generator_output_on_branch_is_allowed(self):
        generated = self.generated_index()
        head = self.commit_bytes(self.work, generated)
        res = self.run_gate(head)
        self.assertEqual(res.returncode, 0, res.stdout + res.stderr)

    def test_hand_edit_of_generator_output_is_blocked(self):
        generated = self.generated_index()
        self.advance_main("index v2 from main\n")
        self.merge_main()
        head = self.commit_bytes(self.work, generated + b"hand edit\n")
        res = self.run_gate(head)
        self.assertEqual(res.returncode, 1, res.stdout + res.stderr)
        self.assertIn(self.INDEX, res.stderr)

    def test_generator_missing_in_pushed_tree_fails_closed(self):
        generated = self.generated_index()
        self.advance_main("index v2 from main\n")
        self.merge_main()
        self.git(self.work, "rm", "-q", "tools/gen_tool_index.py")
        head = self.commit_bytes(self.work, generated)
        res = self.run_gate(head)
        self.assertEqual(res.returncode, 1, res.stdout + res.stderr)
        self.assertIn(self.INDEX, res.stderr)

    def test_generator_crash_in_pushed_tree_fails_closed(self):
        generated = self.generated_index()
        self.advance_main("index v2 from main\n")
        self.merge_main()
        self._write(self.work, "tools/gen_tool_index.py",
                    "import sys\nsys.exit(3)\n")
        head = self.commit_bytes(self.work, generated)
        res = self.run_gate(head)
        self.assertEqual(res.returncode, 1, res.stdout + res.stderr)
        self.assertIn(self.INDEX, res.stderr)

    def test_allow_generated_override_still_passes_an_unverifiable_generator(self):
        generated = self.generated_index()
        self.advance_main("index v2 from main\n")
        self.merge_main()
        self.git(self.work, "rm", "-q", "tools/gen_tool_index.py")
        head = self.commit_bytes(self.work, generated)
        res = self.run_gate(head, {generated_paths.ALLOW_ENV: "1"})
        self.assertEqual(res.returncode, 0, res.stdout + res.stderr)


